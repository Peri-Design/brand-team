test('赵瑞秀首次登录后绑定管理员身份，同名账号不会继承权限', async () => {
  const store = new MemoryStore({ bootstrapAdminName: '赵瑞秀' });
  const owner = await store.upsertUser({ openId: 'ou_owner', name: '赵瑞秀' });
  const duplicateName = await store.upsertUser({ openId: 'ou_other', name: '赵瑞秀' });
  assert.equal(owner.isAdmin, true);
  assert.equal(owner.accessStatus, 'active');
  assert.equal(duplicateName.isAdmin, false);
  assert.equal(duplicateName.accessStatus, 'none');
  assert.equal((await store.upsertUser({ openId: 'ou_owner', name: '赵瑞秀' })).isAdmin, true);
});

test('普通成员登录后等待管理员批准，批准与停用状态可以切换', async () => {
  const store = new MemoryStore({ bootstrapAdminName: '管理员' });
  const admin = await store.upsertUser({ openId: 'ou_admin', name: '管理员' });
  const member = await store.upsertUser({ openId: 'ou_member', name: '设计师' });
  assert.equal(member.accessStatus, 'none');
  assert.equal((await store.setUserAccess(member.openId, 'active', admin.openId)).accessStatus, 'active');
  assert.equal((await store.setUserAccess(member.openId, 'suspended', admin.openId)).accessStatus, 'suspended');
  assert.equal(await store.setUserAccess(admin.openId, 'suspended', admin.openId), null);
});

test('云端文件按飞书用户隔离并通过版本号阻止覆盖', async () => {
  const store = new MemoryStore();
  await store.upsertUser({ openId: 'ou_a', name: 'A' });
  await store.upsertUser({ openId: 'ou_b', name: 'B' });
  const created = await store.createProject('ou_a', '项目 A', { version: 1, name: '项目 A' }, 24);
  assert.equal((await store.listProjects('ou_a')).length, 1);
  assert.equal((await store.listProjects('ou_b')).length, 0);
  assert.equal(await store.getProject('ou_b', created.id), null);
  const updated = await store.updateProject('ou_a', created.id, '项目 A2', { version: 1, name: '项目 A2' }, 25, 1);
  assert.equal(updated.project.revision, 2);
  const conflict = await store.updateProject('ou_a', created.id, '旧页面', { version: 1, name: '旧页面' }, 25, 1);
  assert.equal(conflict.conflict, true);
  assert.equal(conflict.project.revision, 2);
});

