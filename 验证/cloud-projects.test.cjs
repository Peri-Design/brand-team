test('云端文件支持移入回收站、恢复与永久删除', async () => {
  const store = new MemoryStore();
  await store.upsertUser({ openId: 'ou_trash', name: 'Trash' });
  await store.upsertUser({ openId: 'ou_other', name: 'Other' });
  const created = await store.createProject('ou_trash', '待删除文件', { version: 1, name: '待删除文件' }, 40);
  assert.equal(await store.moveProjectToTrash('ou_trash', created.id), true);
  assert.equal((await store.listProjects('ou_trash')).length, 0);
  assert.equal((await store.listProjects('ou_trash', { trashed: true })).length, 1);
  assert.equal(await store.getProject('ou_trash', created.id), null);
  assert.equal(await store.restoreProject('ou_trash', created.id), true);
  assert.equal((await store.listProjects('ou_trash')).length, 1);
  assert.equal((await store.listProjects('ou_trash', { trashed: true })).length, 0);
  assert.equal(await store.moveProjectToTrash('ou_trash', created.id), true);
  assert.equal(await store.purgeProject('ou_trash', created.id), true);
  assert.equal((await store.listProjects('ou_trash', { trashed: true })).length, 0);
  const first = await store.createProject('ou_trash', '待清空 1', { version: 1, name: '待清空 1' }, 20);
  const second = await store.createProject('ou_trash', '待清空 2', { version: 1, name: '待清空 2' }, 20);
  const other = await store.createProject('ou_other', '其他成员文件', { version: 1, name: '其他成员文件' }, 20);
  await store.moveProjectToTrash('ou_trash', first.id);
  await store.moveProjectToTrash('ou_trash', second.id);
  await store.moveProjectToTrash('ou_other', other.id);
  assert.equal(await store.purgeTrash('ou_trash'), 2);
  assert.equal((await store.listProjects('ou_trash', { trashed: true })).length, 0);
  assert.equal((await store.listProjects('ou_other', { trashed: true })).length, 1, '清空回收站不能删除其他成员文件');
});

